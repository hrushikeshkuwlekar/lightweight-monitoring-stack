#!/usr/bin/env bash
# generate-k8s.sh — regenerate the raw k8s/ manifests from the Helm chart so
# they cannot drift. Writes a single multi-doc file at k8s/generated.yaml.
#
# Usage: ./scripts/generate-k8s.sh [--check]
#   --check  render into a temp file and diff against k8s/generated.yaml;
#            exit non-zero if they differ.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CHART="$ROOT/helm/lightweight-monitoring-stack"
OUT="$ROOT/k8s/generated.yaml"

render() {
  helm template demo "$CHART" \
    --namespace monitoring \
    --set namespaces.create=true \
    --set profile=laptop \
    --set grafana.adminPassword=change-me \
    "$@"
}

HEADER="# AUTO-GENERATED by scripts/generate-k8s.sh — do not edit by hand.
# Rendered from the Helm chart with profile=laptop. Apply with: make up
# Regenerate with: make k8s-regen   |   Verified in CI by: make k8s-check
# Grafana admin password is the placeholder 'change-me' (anonymous access is on).
"

if [[ "${1:-}" == "--check" ]]; then
  TMP=$(mktemp)
  trap 'rm -f "$TMP"' EXIT
  { echo "$HEADER"; render; } > "$TMP"
  if ! diff -u "$OUT" "$TMP" >/dev/null 2>&1; then
    echo "ERROR: k8s/generated.yaml is out of sync with the Helm chart." >&2
    echo "       Run: make k8s-regen" >&2
    diff -u "$OUT" "$TMP" | head -60 >&2
    exit 1
  fi
  echo "k8s/generated.yaml is in sync."
else
  { echo "$HEADER"; render; } > "$OUT"
  echo "Wrote $OUT ($(wc -l < "$OUT") lines)."
fi
